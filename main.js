var ScreenWakeLock = class {
  constructor() {
    this.sentinel = null;
    this.wanted = false;
    this.listening = false;
    this.onVisibility = () => {
      void this.reacquire();
    };
  }
  get held() {
    return this.sentinel !== null && !this.sentinel.released;
  }
  // 取得できたら true。非対応・拒否なら false。
  async acquire() {
    this.wanted = true;
    if (!this.listening) {
      document.addEventListener("visibilitychange", this.onVisibility);
      this.listening = true;
    }
    return this.request();
  }
  async release() {
    this.wanted = false;
    if (this.listening) {
      document.removeEventListener("visibilitychange", this.onVisibility);
      this.listening = false;
    }
    const s = this.sentinel;
    this.sentinel = null;
    if (s && !s.released) {
      try {
        await s.release();
      } catch (e) {
      }
    }
  }
  async request() {
    if (this.held)
      return true;
    const api = navigator.wakeLock;
    if (!api)
      return false;
    try {
      const s = await api.request("screen");
      s.addEventListener("release", () => {
        if (this.sentinel === s)
          this.sentinel = null;
      });
      this.sentinel = s;
      return true;
    } catch (e) {
      return false;
    }
  }
  // 表示に戻ったときの取り直し。hidden の間の request() は必ず失敗するので試さない。
  async reacquire() {
    if (!this.wanted || document.visibilityState !== "visible")
      return;
    await this.request();
  }
};

